use super::*;

#[test]
fn readiness_bitmap_matches_the_renderer_horizontal_expansion() {
    let bitmap = [
        0x00, 0x00, 0x0c, 0x00, 0x0c, 0x00, 0xff, 0xfe, 0x0c, 0x00, 0x0c, 0x00, 0x0f, 0xf0, 0x1c,
        0xd8, 0x3c, 0xcc, 0x6c, 0xc4, 0x6c, 0xc6, 0xcd, 0x86, 0xc7, 0x86, 0xee, 0x0c, 0x78, 0x1c,
        0x00, 0xf0,
    ];

    assert_eq!(
        rendered_probe_bitmap(&bitmap).unwrap(),
        [
            0x00, 0x00, 0x1c, 0x00, 0x1c, 0x00, 0xff, 0xfe, 0x1c, 0x00, 0x1c, 0x00, 0x1f, 0xf0,
            0x3d, 0xf8, 0x7d, 0xdc, 0xfd, 0xcc, 0xfd, 0xce, 0xdf, 0x8e, 0xcf, 0x8e, 0xfe, 0x1c,
            0xf8, 0x3c, 0x01, 0xf0,
        ]
    );
}

#[test]
fn readiness_bitmap_rejects_a_partial_glyph() {
    let error = rendered_probe_bitmap(&[0; 30]).unwrap_err();

    assert!(error.to_string().contains("16 rows"));
}
